// PER-FILE LICENCE LIST FOR LICENSE (user, 16 Oct 2026, message 143 (2)). Every data file the page serves (profiles.json and
// the data files in nodal/), each with the licence its own metadata states. Generated, never edited by hand:
//   node licence_list.js testroot --write    rewrites the block in LICENSE
//   node licence_list.js testroot            exits 1 if the block in LICENSE differs from the files
// validate_structure runs the same comparison. A file with no licence field is listed as such; no licence is chosen here.
const fs = require('fs'), path = require('path');
const BEGIN = '--- Data files and their licences (generated by harness/licence_list.js from each file\'s own metadata; do not edit by hand) ---';
const END = '--- End of the generated list ---';

// The licence a file states: meta.licence (or _meta / metadata, or a top-level licence) in JSON and GeoJSON, a '# licence:'
// header line in CSV. null when it states none.
function fileLicence(p){
  if (/\.csv$/.test(p)){
    const m = fs.readFileSync(p, 'utf8').slice(0, 4000).match(/^#\s*licen[cs]e\s*[:=]\s*(.*)$/im);
    return m ? m[1].trim() : null;
  }
  let d; try { d = JSON.parse(fs.readFileSync(p, 'utf8')); } catch (e) { return null; }
  if (!d || typeof d !== 'object' || Array.isArray(d)) return null;
  for (const mk of ['meta', '_meta', 'metadata']){
    const m = d[mk];
    if (m && typeof m === 'object') for (const k of ['licence', 'license']) if (typeof m[k] === 'string') return m[k];
  }
  for (const k of ['licence', 'license']) if (typeof d[k] === 'string') return d[k];
  return null;
}
function dataFiles(root){
  const nodal = fs.readdirSync(path.join(root, 'nodal')).filter(f => /\.(json|csv|geojson)$/.test(f)).sort();
  return ['profiles.json', ...nodal.map(f => 'nodal/' + f)];
}
function block(root){
  const lines = dataFiles(root).map(f => {
    const l = fileLicence(path.join(root, f));
    return '- ' + f + ': ' + (l ? l.replace(/\s+/g, ' ').trim() : 'no licence stated in the file');
  });
  return [BEGIN, ...lines, END].join('\n');
}
// The block as it stands in LICENSE, or null if LICENSE has none.
function blockInLicense(root){
  const t = fs.readFileSync(path.join(root, 'LICENSE'), 'utf8'), a = t.indexOf(BEGIN), b = t.indexOf(END);
  return (a < 0 || b < a) ? null : t.slice(a, b + END.length);
}
module.exports = { block, blockInLicense, dataFiles, fileLicence, BEGIN, END };

if (require.main === module){
  const root = process.argv[2] || 'testroot', want = block(root), have = blockInLicense(root);
  if (process.argv.includes('--write')){
    const f = path.join(root, 'LICENSE'); let t = fs.readFileSync(f, 'utf8');
    if (have) t = t.replace(have, want);
    else {
      const at = t.indexOf('Users are responsible');
      if (at < 0) throw new Error('LICENSE: no place to insert the list');
      t = t.slice(0, at) + want + '\n\n' + t.slice(at);
    }
    fs.writeFileSync(f, t);
    console.log('LICENSE: ' + dataFiles(root).length + ' data files listed');
  } else {
    console.log(have === want ? 'LICENSE list matches the files' : 'LICENSE list differs from the files');
    process.exit(have === want ? 0 : 1);
  }
}
