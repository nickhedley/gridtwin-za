"""731: write queue12.sh. Battery against corridor, central build, 2035 and 2040, weather 2025 and 2015, on today's corridors (one circuit dropped) and
with the full TDP's lines: lithium added at the four binding exits (North West, Northern Cape, Hydra Central, Eastern Cape, equal shares) in steps of
1, 2, 5 and 10 GW at 4 h and 8 h (fixed build, hourly, no commitment floor, as 722 (a)); and corridor additions at R10,000 and R21,700 per MW-km
capped at the same annual cost as each lithium step. A budget at or above the unconstrained expansion's cost repeats the unconstrained case, so
those are not run and the unconstrained case (run first where missing) stands for them. usage: python3 gen_queue12.py > queue12.sh"""
import json, os
S = '/tmp/claude-0/-home-user-gridtwin-za/ff25664d-5d95-5cb3-a5ba-9894dfa04a8f/scratchpad/'
AREAS = ['North West', 'Northern Cape', 'Hydra Central', 'Eastern Cape']
STEPS = [1000, 2000, 5000, 10000]; HOURS = [4, 8]; PRICES = [10000, 21700]
def costs(y):
    c = json.load(open(S + f'engine_final_{y}_wy2025.json'))['costs']; T = c['tech']
    return 1000 * (T['batt']['netAnnuity'] + (T['batt']['gridConn'] or 0)), 1000 * c['battEnergyRkWhyr']
print('#!/bin/bash\n# Twelfth queue (message 731), generated by gen_queue12.py. Resumable.\nS=' + S.rstrip('/') + '; R=$S/sc/run_net.sh; W=$S/wt-05f; P=engine_final; T=$S/tdp_lines_full.json\necho "queue12 pid $$ start $(date -u +%FT%H:%MZ)" >> $S/run_net_progress.txt')
n = 0
for y in (2035, 2040):
    cb, ce = costs(y)
    for wy in (2025, 2015):
        for case, tdp in (('n1c', ''), ('n1ctdp', 'TDP_FILE=$T ')):
            # the unconstrained extendable cases at both prices, run first where missing (run_net.sh skips existing output)
            for px in PRICES:
                sfx = '_ext10k' if px == 10000 else '_ext21k'
                print(f'{tdp}SUFFIX={"_tdpfull" if tdp else ""}{sfx} TX_EXT={px} DISC=0.08 bash $R $W $P "{y} {wy} {case} reea 0 0"'); n += 1
            for mw in STEPS:
                for h in HOURS:
                    add = ','.join(f'{a}:{mw / 4:.0f}' for a in AREAS); rbn = (mw * cb + mw * h * ce)
                    print(f'{tdp}SUFFIX={"_tdpfull" if tdp else ""}_li{mw // 1000}g{h}h BATT_ADD="{add}" BATT_ADD_H={h} bash $R $W $P "{y} {wy} {case} reea 0 0"'); n += 1
                    for px in PRICES:
                        sfx = '_ext10k' if px == 10000 else '_ext21k'
                        unc = f'$S/net_final_{y}_wy{wy}_{case}_reea_l0_c0{"_tdpfull" if tdp else ""}{sfx}.json'
                        print(f'{tdp}SUFFIX={"_tdpfull" if tdp else ""}{sfx}_b{mw // 1000}g{h}h TX_EXT={px} DISC=0.08 bash $S/sc/run_budget.sh {unc} {rbn:.0f} $W $P "{y} {wy} {case} reea 0 0"   # budget R{rbn / 1e9:.3f}bn a year, skipped when above the unconstrained cost'); n += 1
print('echo "queue12 done $(date -u +%FT%H:%MZ)" >> $S/run_net_progress.txt')
print(f'# {n} cases listed; the budget cases whose budget exceeds the unconstrained cost solve to the unconstrained case quickly', )
